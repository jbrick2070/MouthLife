/**
 * Embeds the city skyline drawings into the native Apple app.
 *
 *   npx vite-node scripts/skyline-native.ts --write  writes CitySkylineArt.swift
 *   npx vite-node scripts/skyline-native.ts --check  fails if that file is out of date
 *
 * The web game reads src/config/skylines/<city>.txt directly. The native app gets the same text as
 * Swift string constants, plus what the web parser makes of each drawing (piece and triangle counts
 * and a checksum), so the Swift tests can prove both editions build the same shapes.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { parseCityArt, type SkylinePiece } from '../src/config/citySkylineGeometry';
import { CITY_SKYLINE_TEXT } from '../src/config/citySkylines';

export const SKYLINE_SWIFT_PATH = join(
  process.cwd(),
  'native-apple',
  'Sources',
  'MouthLifeCore',
  'Config',
  'CitySkylineArt.swift'
);

/** One number that changes if any triangle moves; both editions must agree on it. */
export function skylineChecksum(pieces: readonly SkylinePiece[]): number {
  let sum = 0;
  for (const piece of pieces) {
    for (let i = 0; i < piece.tris.length; i += 2) sum += piece.tris[i] + piece.tris[i + 1] * 1.37;
  }
  return Math.round(sum * 1000) / 1000;
}

function summary(pieces: readonly SkylinePiece[], motions: number): string {
  const lights = pieces.filter((p) => p.light).length;
  const triangles = pieces.reduce((n, p) => n + p.tris.length / 6, 0);
  const shaded = pieces.filter((p) => p.topColor !== null).length;
  const moving = pieces.filter((p) => p.group > 0).length;
  return (
    `Expected(pieces: ${pieces.length}, lightPieces: ${lights}, triangles: ${triangles}, ` +
    `checksum: ${skylineChecksum(pieces)}, shadedPieces: ${shaded}, movingPieces: ${moving}, motions: ${motions})`
  );
}

const constName = (hostId: string): string => hostId.replace(/_([a-z])/g, (_m, c: string) => c.toUpperCase());

export function renderSkylineSwift(): string {
  const hosts = Object.keys(CITY_SKYLINE_TEXT).sort();
  let swift = `// GENERATED by scripts/skyline-native.ts from src/config/skylines/*.txt. Do not edit by hand.
// Run \`npx vite-node scripts/skyline-native.ts --write\` after a drawing changes.

public enum CitySkylineArt {
    /// What the web edition's parser makes of a drawing. The Swift tests compare against it.
    public struct Expected: Equatable, Sendable {
        public let pieces: Int
        public let lightPieces: Int
        public let triangles: Int
        public let checksum: Double
        public let shadedPieces: Int
        public let movingPieces: Int
        public let motions: Int
    }

    public static let hostIds: [String] = [${hosts.map((h) => `"${h}"`).join(', ')}]

    /// The drawing for a host city (WorldCartridge.hostId), in the format CitySkyline.parse reads.
    public static func text(forHost hostId: String) -> String? {
        switch hostId {
${hosts.map((h) => `        case "${h}": return ${constName(h)}`).join('\n')}
        default: return nil
        }
    }

    public static func expectedSkyline(forHost hostId: String) -> Expected? {
        switch hostId {
${hosts.map((h) => `        case "${h}": return ${summary(parseCityArt(CITY_SKYLINE_TEXT[h]).skyline, parseCityArt(CITY_SKYLINE_TEXT[h]).motions.length)}`).join('\n')}
        default: return nil
        }
    }

    public static func expectedProp(forHost hostId: String) -> Expected? {
        switch hostId {
${hosts.map((h) => `        case "${h}": return ${summary(parseCityArt(CITY_SKYLINE_TEXT[h]).prop, 0)}`).join('\n')}
        default: return nil
        }
    }
`;
  for (const host of hosts) {
    const text = CITY_SKYLINE_TEXT[host].replace(/\r\n/g, '\n').replace(/\s+$/, '');
    if (text.includes('"""')) throw new Error(`${host}: a drawing cannot contain three double quotes`);
    swift += `\n    static let ${constName(host)} = #"""\n${text}\n"""#\n`;
  }
  swift += '}\n';
  return swift;
}

// Runs only when asked to with --write or --check, so a test can import this file safely.
const invoked = process.argv.includes('--write') || process.argv.includes('--check');
if (invoked) {
  const swift = renderSkylineSwift();
  if (process.argv.includes('--check')) {
    let onDisk = '';
    try {
      onDisk = readFileSync(SKYLINE_SWIFT_PATH, 'utf8').replace(/\r\n/g, '\n');
    } catch {
      /* missing counts as stale */
    }
    if (onDisk !== swift) {
      console.error('CitySkylineArt.swift is out of date. Run: npx vite-node scripts/skyline-native.ts --write');
      process.exit(1);
    }
    console.log('CitySkylineArt.swift is up to date.');
  } else {
    writeFileSync(SKYLINE_SWIFT_PATH, swift);
    console.log(`Wrote ${SKYLINE_SWIFT_PATH}`);
  }
}
