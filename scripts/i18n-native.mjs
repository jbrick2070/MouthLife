#!/usr/bin/env node
/**
 * Embeds the shared translation files into the native Apple app.
 *
 *   node scripts/i18n-native.mjs          writes native-apple/Sources/MouthLifeCore/Config/L10nCatalogs.swift
 *   node scripts/i18n-native.mjs --check  fails if that file is out of date
 *
 * The web game loads src/i18n/locales/<lang>.json directly. The native app gets the same JSON as
 * Swift string constants, so both editions always show the same translations and the Xcode project
 * needs no resource files.
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(fileURLToPath(import.meta.url), '..', '..');
const LOCALES = join(ROOT, 'src', 'i18n', 'locales');
const OUT = join(ROOT, 'native-apple', 'Sources', 'MouthLifeCore', 'Config', 'L10nCatalogs.swift');

const langs = readdirSync(LOCALES)
  .filter((f) => /^[a-z]{2}\.json$/.test(f))
  .map((f) => f.slice(0, 2))
  .sort();

let swift = `// GENERATED by scripts/i18n-native.mjs from src/i18n/locales/*.json. Do not edit by hand.
// Run \`node scripts/i18n-native.mjs\` after translations change.

enum L10nCatalogs {
    static let languageCodes: [String] = [${langs.map((l) => `"${l}"`).join(', ')}]

    /// JSON object mapping English on-screen text to its translation.
    static func json(for languageCode: String) -> String? {
        switch languageCode {
${langs.map((l) => `        case "${l}": return ${l}`).join('\n')}
        default: return nil
        }
    }
`;
for (const lang of langs) {
  const catalog = JSON.parse(readFileSync(join(LOCALES, `${lang}.json`), 'utf8'));
  // One entry per line keeps diffs readable. A raw string needs no escaping beyond JSON's own.
  const json = JSON.stringify(catalog, null, 0)
    .replace(/^\{/, '{\n')
    .replace(/\}$/, '\n}')
    .replace(/","/g, '",\n"');
  if (json.includes('"""###')) throw new Error(`${lang}.json contains the raw-string terminator`);
  swift += `\n    private static let ${lang}: String = ###"""\n${json}\n"""###\n`;
}
swift += '}\n';

if (process.argv.includes('--check')) {
  if (readFileSync(OUT, 'utf8') !== swift) {
    console.error('L10nCatalogs.swift is out of date. Run: node scripts/i18n-native.mjs');
    process.exit(1);
  }
  console.log(`L10nCatalogs.swift is up to date (${langs.length} languages).`);
} else {
  writeFileSync(OUT, swift);
  console.log(`Wrote L10nCatalogs.swift with ${langs.length} languages (${Math.round(swift.length / 1024)} KB).`);
}
